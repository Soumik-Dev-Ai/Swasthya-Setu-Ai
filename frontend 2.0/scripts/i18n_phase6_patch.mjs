const PATH = "src/i18n.ts";
let src = readFileSync(PATH, "utf8");
let report = [];

function applyReplacements(block, entries, label) {
  for (const [key, value] of Object.entries(entries)) {
    const re = new RegExp(`"${key}": "[^"]*"`);
    if (!re.test(block)) throw new Error(`${label}: key "${key}" not found for replacement`);
    block = block.replace(re, () => `"${key}": "${value}"`);
  }
  return block;
}

// en: 6C honesty replacements only.
{
  const m = src.match(/const en: Dict = \{[\s\S]*?\n\}/);
  if (!m) throw new Error("en dict not found");
  src = src.replace(m[0], () => applyReplacements(m[0], EN_REPLACE, "en"));
  report.push(`en: ${Object.keys(EN_REPLACE).length} values replaced (6C)`);
}

// Indic locales: 6A/6C replacements + 6B insertions.
for (const [loc, { replace, fresh }] of Object.entries(LOCALES)) {
  const blockRe = new RegExp(`const ${loc}: Dict = \\{[\\s\\S]*?\\n\\}`);
  const m = src.match(blockRe);
  if (!m) throw new Error(`${loc} dict not found`);
  let block = applyReplacements(m[0], replace, loc);

  const freshLines = Object.entries(fresh)
    .map(([k, v]) => `  "${k}": "${v}",`)
    .join("\n");
  const anchor = `const ${loc}: Dict = {`;
  if (!block.includes(anchor)) throw new Error(`${loc}: anchor not found`);
  if (block.includes('"c.directions"')) throw new Error(`${loc}: already patched — aborting (not idempotent)`);
  block = block.replace(anchor, () =>
    `${anchor}\n  // phase-6 localization pass (6A/6B/6C)\n${freshLines}`);
  src = src.replace(m[0], () => block);
  report.push(`${loc}: ${Object.keys(fresh).length} keys added, ${Object.keys(replace).length} replaced`);
}

writeFileSync(PATH, src, "utf8");
